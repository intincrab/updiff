import { registrableDomain } from './hosts.ts';
import type { CodeKind, DiffReport, Finding, Severity, Snapshot } from './types.ts';
import { formatBytes } from './util.ts';

export const HOSTNAME_CAVEAT =
  'A hostname found in the code is not proof that the app connects to it. It shows what the code mentions: endpoints, links and sometimes dead code.';

const SEVERITY_LABEL: Record<Severity, string> = { high: 'High', notable: 'Notable', info: 'Info' };
const CHANGE_MARK: Record<Finding['change'], string> = { added: '+', removed: '-', changed: '~' };

interface Palette {
  bold(s: string): string;
  dim(s: string): string;
  sev(sev: Severity, s: string): string;
}

const plain: Palette = { bold: (s) => s, dim: (s) => s, sev: (_, s) => s };
const ansi: Palette = {
  bold: (s) => `\x1b[1m${s}\x1b[22m`,
  dim: (s) => `\x1b[2m${s}\x1b[22m`,
  sev: (sev, s) => `\x1b[${sev === 'high' ? 31 : sev === 'notable' ? 33 : 36}m${s}\x1b[39m`,
};

function clip(s: string, max: number): string {
  return s.length > max ? `${s.slice(0, max - 1)}… (${s.length - max + 1} more characters; use --format md or json for all)` : s;
}

export function renderText(report: DiffReport, options: { color?: boolean; full?: boolean } = {}): string {
  const p = options.color ? ansi : plain;
  const max = options.full ? Infinity : 400;
  const lines: string[] = [];
  lines.push(p.bold(`${report.app.name}  ${report.from.version} (${report.from.build}) → ${report.to.version} (${report.to.build})`));
  lines.push(p.dim(`${report.app.bundleId}`));
  lines.push(
    `${p.sev('high', `${report.counts.high} high`)} · ${p.sev('notable', `${report.counts.notable} notable`)} · ${p.sev('info', `${report.counts.info} info`)}`,
  );
  if (report.identical) {
    lines.push('', 'No changes: both sides have the same sealed contents.');
    return lines.join('\n') + '\n';
  }
  for (const sev of ['high', 'notable', 'info'] as Severity[]) {
    const group = report.findings.filter((f) => f.severity === sev);
    if (!group.length) continue;
    lines.push('', p.sev(sev, p.bold(SEVERITY_LABEL[sev].toUpperCase())));
    for (const f of group) {
      lines.push(`  ${p.sev(sev, CHANGE_MARK[f.change])} ${f.title}`);
      if (f.detail) lines.push(`      ${clip(f.detail, max)}`);
      if (f.where?.length) lines.push(p.dim(`      at ${f.where.join(', ')}`));
    }
  }
  for (const note of report.notes ?? []) lines.push('', p.dim(`Note: ${note}`));
  if (report.findings.some((f) => f.category === 'host')) lines.push('', p.dim(HOSTNAME_CAVEAT));
  return lines.join('\n') + '\n';
}

function mdEscape(s: string): string {
  return s.replace(/([\\`*_[\]<>|])/g, '\\$1');
}

export function renderMarkdown(report: DiffReport): string {
  const lines: string[] = [];
  lines.push(`# ${mdEscape(report.app.name)}: ${report.from.version} → ${report.to.version}`, '');
  lines.push(`\`${report.app.bundleId}\` · build ${report.from.build} → ${report.to.build}`, '');
  lines.push(`| | From | To |`, `|---|---|---|`);
  lines.push(`| Snapshot | ${report.from.takenAt} | ${report.to.takenAt} |`);
  lines.push(`| Path | \`${report.from.path}\` | \`${report.to.path}\` |`, '');
  lines.push(`**${report.counts.high} high · ${report.counts.notable} notable · ${report.counts.info} info**`, '');
  if (report.identical) {
    lines.push('No changes: both sides have the same sealed contents.', '');
    return lines.join('\n');
  }
  for (const sev of ['high', 'notable', 'info'] as Severity[]) {
    const group = report.findings.filter((f) => f.severity === sev);
    if (!group.length) continue;
    lines.push(`## ${SEVERITY_LABEL[sev]}`, '');
    for (const f of group) {
      lines.push(`- ${CHANGE_MARK[f.change] === '+' ? 'Added' : CHANGE_MARK[f.change] === '-' ? 'Removed' : 'Changed'}: **${mdEscape(f.title)}**`);
      if (f.detail) lines.push(`  ${mdEscape(f.detail)}`);
      if (f.where?.length) lines.push(`  <sub>${f.where.map((w) => `\`${w}\``).join(', ')}</sub>`);
    }
    lines.push('');
  }
  for (const note of report.notes ?? []) lines.push(`> Note: ${mdEscape(note)}`, '');
  if (report.findings.some((f) => f.category === 'host')) lines.push(`> ${HOSTNAME_CAVEAT}`, '');
  lines.push('<sub>Generated by updiff. Static inspection only: the app was not run.</sub>', '');
  return lines.join('\n');
}

export function renderJson(value: unknown): string {
  return JSON.stringify(value, null, 2) + '\n';
}

const KIND_PLURAL: Record<CodeKind, string> = {
  main: 'main executable',
  helperApp: 'helper apps',
  xpcService: 'XPC services',
  appExtension: 'app extensions',
  loginItem: 'login items',
  privilegedHelper: 'privileged helpers',
  systemExtension: 'system extensions',
  framework: 'frameworks',
  plugin: 'plug-in bundles',
  executable: 'other executables',
  nativeModule: 'native Node modules',
};

export function renderScan(s: Snapshot, options: { color?: boolean } = {}): string {
  const p = options.color ? ansi : plain;
  const main = s.code.find((c) => c.kind === 'main');
  const lines: string[] = [];
  lines.push(p.bold(`${s.app.name} ${s.app.version} (${s.app.build})`), p.dim(`${s.app.bundleId} · ${s.app.path}`), '');
  const sig = s.signing;
  lines.push(
    `Signing        ${sig.status}${sig.teamId ? `, team ${sig.teamId}` : ''}${sig.authorities[0] ? ` (${sig.authorities[0]})` : ''}${sig.hardenedRuntime ? ', hardened runtime' : ', no hardened runtime'}`,
  );
  const ents = Object.keys(main?.entitlements ?? {});
  const sandboxed = main?.entitlements?.['com.apple.security.app-sandbox'] === true;
  if (s.notarization) {
    const n = s.notarization;
    const stapled = n.stapled === undefined ? '' : n.stapled ? ', ticket stapled' : ', ticket not stapled';
    lines.push(`Gatekeeper     ${n.assessment}${n.source ? ` (${n.source})` : ''}${stapled}`);
  }
  if (s.info.appStoreReceipt) lines.push('App Store      yes (bundle has a Mac App Store receipt)');
  lines.push(`Sandbox        ${sandboxed ? 'yes' : 'no'}`);
  lines.push(`Entitlements   ${ents.length ? ents.join(', ') : 'none'}`);
  const privacy = Object.keys(s.info.privacyUsage);
  lines.push(`Privacy asks   ${privacy.length ? privacy.map((k) => k.replace(/^NS/, '').replace(/UsageDescription$/, '')).join(', ') : 'none'}`);
  lines.push(`URL schemes    ${s.info.urlSchemes.length ? s.info.urlSchemes.join(', ') : 'none'}`);
  const sparkle = s.code.some((c) => c.kind === 'framework' && c.path.endsWith('/Sparkle.framework'));
  if (s.info.sparkleFeedUrl) lines.push(`Update feed    ${s.info.sparkleFeedUrl}`);
  for (const [i, url] of (s.info.sparkleFeedsInCode ?? []).entries()) lines.push(`${i === 0 && !s.info.sparkleFeedUrl ? 'Update feed   ' : '              '} ${url} (in code)`);
  if (sparkle && !s.info.sparkleFeedUrl && !s.info.sparkleFeedsInCode?.length) {
    lines.push('Update feed    Sparkle is bundled, but no feed was found (it may be built at runtime)');
  }
  if (s.local?.sparkleFeedInDefaults) lines.push(`               ${s.local.sparkleFeedInDefaults} (set in this Mac's preferences)`);
  if (s.local && (s.local.sparkleAutomaticChecks !== undefined || s.local.sparkleAutomaticallyUpdate !== undefined)) {
    const onOff = (v: boolean | undefined): string => (v === undefined ? 'default' : v ? 'on' : 'off');
    lines.push(`This Mac       automatic update checks ${onOff(s.local.sparkleAutomaticChecks)}, automatic install ${onOff(s.local.sparkleAutomaticallyUpdate)}`);
  }
  const counts = new Map<CodeKind, number>();
  for (const c of s.code) if (c.kind !== 'main') counts.set(c.kind, (counts.get(c.kind) ?? 0) + 1);
  lines.push(`Nested code    ${counts.size ? [...counts].map(([k, n]) => `${n} ${KIND_PLURAL[k]}`).join(', ') : 'none'}`);
  lines.push(
    `Background     ${s.backgroundItems.length ? s.backgroundItems.map((b) => `${b.label ?? b.file}${b.program ? ` → ${b.program}` : ''}`).join(', ') : 'none'}`,
  );
  if (s.electron) {
    lines.push(
      `Electron       ${s.electron.electronVersion ?? 'version unknown'}${s.electron.appSource ? `, code in ${s.electron.appSource}` : ''}, ${Object.keys(s.electron.packages).length} bundled npm packages`,
    );
  }
  const domains = new Set(Object.keys(s.hosts).map(registrableDomain));
  lines.push(`Hostnames      ${Object.keys(s.hosts).length} hosts across ${domains.size} domains`);
  lines.push(
    p.dim(
      `Scanned ${s.stats.filesScanned} files (${formatBytes(s.stats.bytesScanned)}) of ${s.app.fileCount} (${formatBytes(s.app.sizeBytes)}) in ${(s.stats.scanMs / 1000).toFixed(1)} s${s.stats.deep ? ', deep' : ''}`,
    ),
  );
  for (const w of s.stats.warnings) lines.push(p.sev('notable', `warning: ${w}`));
  return lines.join('\n') + '\n';
}
